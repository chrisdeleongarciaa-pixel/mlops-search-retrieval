"""Write the run configurations of Vespa systems for one collection and query set.

    python evaluation/declare_runs.py --name litsearch --collection LABEL --corpus M --transform M \
        --queries M --runtime M [--space M] [--systems bm25 dense] [--hybrid rrf|convex:ALPHA] \
        [--lexical-profile bm25] [--depth 1000] [--out-dir config/runs/generated]

Collection labels exist only once a projection is fed, so these declarations are written on the
host after `vespa_project.py` and committed there. Every file names one code commit (HEAD, or
--code-commit) and is resolved before it is kept: a declaration that does not resolve is not
written. A test report requires its development declaration to name the same code commit.
"""

import argparse
import json
from pathlib import Path
import sys

from search_retrieval.experiment.manifests import read_manifest
from search_retrieval.experiment.provenance import _git
from search_retrieval.experiment.run_config import ConfigError, resolve
from embed import ROOT


def declaration(*, run_id: str, commit: str, split: str, corpus: str, transform: str, collection: str,
                lexical_profile: str | None, profile: str, depth: int, fusion: dict, query_set: dict, queries: str,
                runtime: str, space: str | None) -> str:
    lines = ["# Generated by evaluation/declare_runs.py.", "[run]", f'id = "{run_id}"', f'code_commit = "{commit}"',
             f'split = "{split}"', "", "[corpus]", f'manifest = "{corpus}"', "", "[transform]", f'manifest = "{transform}"', ""]
    if space:
        lines += ["[space.dense]", f'manifest = "{space}"', ""]
    lines += ["[index]", 'engine = "vespa"', f'schema_revision = "{collection}"']
    if lexical_profile:
        lines.append(f'lexical = {{ profile = "{lexical_profile}" }}')
    fusion_text = ", ".join(f"{key} = {json.dumps(value)}" for key, value in fusion.items())
    lines += ["", "[ranking]", f'profile = "{profile}"', f"target_hits = {depth}", f"fusion = {{ {fusion_text} }}", "",
              "[queries]", f'set = "{query_set["name"]}"', f'judgments = "{query_set["judgments"]}"', f'manifest = "{queries}"',
              "", "[runtime]", f'manifest = "{runtime}"', ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    for name in ("name", "collection", "corpus", "transform", "queries", "runtime"):
        parser.add_argument(f"--{name}", required=True)
    parser.add_argument("--space")
    parser.add_argument("--systems", nargs="*", default=["bm25", "dense"], choices=["bm25", "dense"])
    parser.add_argument("--hybrid", help="rrf, or convex:ALPHA")
    parser.add_argument("--lexical-profile", default="bm25")
    parser.add_argument("--depth", type=int, default=1000)
    parser.add_argument("--out-dir", default="config/runs/generated")
    parser.add_argument("--code-commit", help="the code commit to declare (default HEAD); dev and test runs that "
                                              "are compared at report time must name the same one")
    args = parser.parse_args()
    try:
        query_set, _ = read_manifest(ROOT, args.queries, "query-set")
        commit = args.code_commit or _git(ROOT, "rev-parse", "HEAD")
        systems = [(system, {"kind": "none"}) for system in args.systems]
        if args.hybrid:
            kind, _, alpha = args.hybrid.partition(":")
            systems.append(("hybrid", {"kind": "rrf", "k": 60} if kind == "rrf"
                            else {"kind": "convex", "alpha": float(alpha), "normalization": "minmax"}))
        written = []
        for system, fusion in systems:
            needs_space, needs_lexical = system != "bm25", system != "dense"
            if needs_space and not args.space:
                raise ConfigError(f"The {system} system needs --space")
            label = system if system != "hybrid" else f"hybrid-{args.hybrid.replace(':', '-')}"
            relative = f"{args.out_dir}/{args.name}-{query_set['split']}.{label}.toml"
            text = declaration(run_id=f"{args.name}-{query_set['split']}.{label}", commit=commit, split=query_set["split"],
                               corpus=args.corpus, transform=args.transform, collection=args.collection,
                               lexical_profile=args.lexical_profile if needs_lexical else None,
                               profile=f"vespa-{system}", depth=args.depth, fusion=fusion, query_set=query_set,
                               queries=args.queries, runtime=args.runtime, space=args.space if needs_space else None)
            path = ROOT / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(text.encode("utf-8"))
            try:
                resolve(ROOT, relative)
            except Exception:
                path.unlink()
                raise
            written.append(relative)
    except (ConfigError, ValueError, OSError) as error:
        print(f"{type(error).__name__}: {error}", file=sys.stderr)
        return 1
    print(json.dumps({"written": written}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
